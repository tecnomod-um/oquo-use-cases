#!/usr/bin/env bash
# Evaluates the human readability of an ontology with HURON and saves the results
# as OQUO-compliant RDF, together with the oquo-huron module and the values
# converted to the scale of the OQuaRE quality model.
#
# Usage: ./evaluate.sh [ontology IRI]
#   By default, the ontology evaluated is version 2.2.2 of the OQUO core.
#
# The HURON command-line tool does not accept IRIs, so the ontology is first
# downloaded to a temporary file, which is removed at the end. The checksum of its
# content is recorded in source_results/environment.txt.
#
# HURON gives only the results; the module is applied to them by the /applyModel
# method of oquo-instance-creator-endpoint, so the services must be running:
#   cd services && docker compose up -d --build --wait
#
# HURON is run with the jar given in HURON_JAR (by default, huron-0.0.15.jar in this
# folder): with the local Java if there is one, or else in a Docker container.
#
# Outputs:
#   source_results/huron_results.ttl         results of HURON, as generated by its command-line tool
#   source_results/environment.txt           versions used (ontology, HURON, Java)
#   oquo_compliant_results/oquo_model.ttl    results as OQUO-compliant RDF, with the
#                                            oquo-huron module and the converted values
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SERVICES="$ROOT/services"
MODULE_IRI="https://purl.org/oquo-huron"

ONTOLOGY_IRI="${1:-https://purl.org/oquo-core/v2.2.2}"
HURON_JAR="${HURON_JAR:-$HERE/huron-0.0.15.jar}"
HURON_MEMORY="${HURON_MEMORY:-8g}"
JAVA_IMAGE="${JAVA_IMAGE:-eclipse-temurin:17-jre}"

# Port of oquo-instance-creator-endpoint (services/.env), 8000 by default
INSTANCE_CREATOR_PORT="$(grep -E '^OQUO_INSTANCE_CREATOR_PORT=' "$SERVICES/.env" 2>/dev/null | cut -d= -f2 || true)"
INSTANCE_CREATOR_PORT="${INSTANCE_CREATOR_PORT:-8000}"

SOURCE_RESULTS="$HERE/source_results"
OQUO_RESULTS="$HERE/oquo_compliant_results"
mkdir -p "$SOURCE_RESULTS" "$OQUO_RESULTS"

if [ ! -f "$HURON_JAR" ]; then
  echo "[!] HURON jar not found: $HURON_JAR" >&2
  echo "    Download it from https://github.com/tecnomod-um/huron/releases, or give its path in HURON_JAR." >&2
  exit 1
fi

# Temporary folder for the downloaded ontology, removed on exit
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT
ONTOLOGY_FILE="$TMP_DIR/ontology.owl"
HURON_RESULTS="$SOURCE_RESULTS/huron_results.ttl"

echo "[+] Downloading $ONTOLOGY_IRI"
curl -fsSL -H "Accept: application/rdf+xml, text/turtle;q=0.9, */*;q=0.5" \
     "$ONTOLOGY_IRI" -o "$ONTOLOGY_FILE"

echo "[+] Evaluating the ontology with HURON"
if command -v java >/dev/null 2>&1; then
  java -Xmx"$HURON_MEMORY" -jar "$HURON_JAR" \
       --input "$ONTOLOGY_FILE" \
       --output-detailed-rdf "$HURON_RESULTS"
  java_version="$(java -version 2>&1 | head -1)"
else
  echo "[+] No local Java: running HURON in $JAVA_IMAGE"
  docker run --rm \
       -v "$(dirname "$HURON_JAR"):/huron:ro" -v "$TMP_DIR:/ontology:ro" -v "$SOURCE_RESULTS:/results" \
       "$JAVA_IMAGE" \
       java -Xmx"$HURON_MEMORY" -jar "/huron/$(basename "$HURON_JAR")" \
            --input /ontology/ontology.owl \
            --output-detailed-rdf /results/huron_results.ttl
  java_version="$JAVA_IMAGE ($(docker image inspect --format '{{index .RepoDigests 0}}' "$JAVA_IMAGE" 2>/dev/null || echo unknown))"
fi

echo "[+] Results of HURON saved in $HURON_RESULTS"
echo "[+] Applying the module $MODULE_IRI to the results"
curl -fsS -X POST "http://localhost:$INSTANCE_CREATOR_PORT/applyModel" \
     --url-query "ontologyIRI=$MODULE_IRI" \
     -H "Content-Type: text/turtle" \
     --data-binary @"$HURON_RESULTS" \
     -o "$OQUO_RESULTS/oquo_model.ttl"
echo "[+] OQUO-compliant results saved in $OQUO_RESULTS/oquo_model.ttl"

{
  echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "ontology: $ONTOLOGY_IRI"
  echo "ontology sha256: $(sha256sum "$ONTOLOGY_FILE" | cut -d' ' -f1)"
  echo "HURON: $(basename "$HURON_JAR")"
  echo "HURON sha256: $(sha256sum "$HURON_JAR" | cut -d' ' -f1)"
  echo "Java: $java_version"
  echo "OQUO module: $MODULE_IRI"
} >"$SOURCE_RESULTS/environment.txt"
echo "[+] Versions saved in $SOURCE_RESULTS/environment.txt"
