"""Converters of the results of FAIR assessment tools to OQUO-compliant RDF.

- POST /foopsToOquo: results of FOOPS!, described with the module oquo-foops.
- POST /ofaireToOquo: results of O'FAIRe, described with the module oquo-ofaire.

The RDF is generated by oquo-instance-creator-endpoint, at the URL given in the
environment variable OQUO_INSTANCE_CREATOR_URL.
"""
import uvicorn
from fastapi import FastAPI

import foops
import ofaire

app = FastAPI(title="To OQUO converter")
app.include_router(foops.router)
app.include_router(ofaire.router)

if __name__ == '__main__':
    uvicorn.run(app, host="0.0.0.0", port=8001)
